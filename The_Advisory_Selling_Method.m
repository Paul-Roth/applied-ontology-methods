## The Five Common Ways of Selling

The full spectrum from most adversarial to most advisory:

| Position | Approach | Governing Force |
|----------|----------|----------------|
| Conspiratorial | Against the client | Human Nature — deepest |
| Competitive | Against the competition | Human Nature |
| Contract | Against the agreement | Human Nature |
| Consultative | For the client's stated needs | Transitional |
| Collaborative | With the client | Human Spirit |
| Advisory | For the client's full possibility | Human Spirit — deepest |

Most advisors operate somewhere in the middle of this spectrum — believing they are collaborative or consultative while the machinery continues to run adversarial patterns beneath the surface.

The Advisory Selling Method installs the capacity to operate consistently from the Advisory position — not through better technique, but through the same ontological shift the Blindspot Method produces.

