## The Project Frame

The Advisory Selling Method redefines what selling actually is:

> *"Selling is working with clients to create a vision of a future possibility compelling enough to change their actions in the present."*

The word **project** is precise. A project is a projection into the future — a vision of what becomes possible if the client acts now. The advisor's role is not to present a product. It is to co-create a vision compelling enough that the client chooses to move toward it.

> *"Clients are not buying your product. They are buying the vision of what it will do for them in the future."*

This reframe changes everything about how a conversation is designed, conducted, and completed.

