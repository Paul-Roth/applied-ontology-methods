## The Four Adversarial Selling Strategies

The machinery produces four primary adversarial strategies — each with a surface presentation that obscures its adversarial nature:

- **Aggressive** — force through pressure
- **Aversive** — force through withdrawal
- **Apathetic** — force through indifference
- **Attentive** — force through excessive accommodation

The fifth — **Authentic** — is the Advisory position. It is not a strategy. It is the natural expression of an advisor operating from Human Spirit.

---

## The Five Modes of Influence

The machinery produces four adversarial modes of influence:

- **Inductive** — leading to a predetermined conclusion
- **Deductive** — reasoning toward a predetermined conclusion
- **Reductive** — simplifying to eliminate resistance
- **Seductive** — appealing to desire to bypass judgment

The fifth — **Eductive** — is the Advisory mode. Drawing out the client's own commitment rather than pushing in the advisor's agenda.

> *"Eduction — to draw out, not push in."*

Eduction is not a technique applied over the top of the other four modes. It is what becomes natural when the advisor's Human Spirit is governing the conversation rather than their machinery.

