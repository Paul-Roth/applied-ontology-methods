## The Influencing Action Tripod

Three legs are required for an advisor to influence client action. Remove any one and the structure collapses:

1. **Knowledge** — the advisor's depth of understanding of their domain
2. **Problem-Solving** — the capacity to work with the client's actual situation
3. **The Client's Project** — the vision of future possibility the client is moving toward

Most advisors have the first two legs. The third — the Client's Project — is what the Advisory Selling Method installs. Without it, knowledge and problem-solving produce a presentation. With it, they produce a partnership.

