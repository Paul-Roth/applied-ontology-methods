## The Six Advisory Selling Modules

The Advisory Selling Method is structured around six complete modules — each addressing a distinct domain of the advisory relationship:

**Module 1: Building Partnerships**
Establishing the foundation of Receptive Listening and genuine collaborative intent.

**Module 2: Presenting with Power**
Delivering a vision of future possibility rather than a product presentation.

**Module 3: Launching Projects**
Moving from vision to commitment — the client's freely given decision to proceed.

**Module 4: Managing Accountability**
Holding the project — and the relationship — to its highest possibility throughout execution.

**Module 5: Creating Breakthroughs**
Working with the client when the project encounters the machinery — their own or the system's.

**Module 6: Completing Projects**
Closing in the deepest sense — completing what was begun, honoring what was created, and establishing the ground for what comes next.

