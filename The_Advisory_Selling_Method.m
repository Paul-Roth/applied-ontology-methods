# The Advisory Selling Method™

## Overview

The Advisory Selling Method is the Applied Ontological Method extended into the domain of selling and human conversation. It restores selling to what it was always meant to be — Inceptive, not Deceptive; Eductive, not Aggressive; built on commitment freely given rather than compliance extracted by force.

It is not a sales technique. It is not a closing methodology. It is not a script or a sequence of persuasion moves.

It is the application of the same foundational equation — Human Nature + Human Spirit = Human Being — to the most consequential domain of human interaction: the conversation in which one person attempts to move another toward a new possibility.

> *"We must learn to transform selling from the set of cheap tricks it has become into the sacred act it was always meant to be."*

---

## Why It Matters

Every human conversation is a selling conversation. Not every conversation involves a product or a price. But every conversation in which one person attempts to move another — toward a decision, a commitment, a change in behavior, a new way of seeing — is a selling conversation.

The machinery runs in selling exactly as it runs everywhere else. Human Nature produces the adversarial, agenda-driven, survival-oriented selling that has made the word itself a source of resistance. Human Spirit produces the Inceptive, commitment-based, service-driven selling that was always possible and almost never practiced.

The Advisory Selling Method is the Technology that makes the shift from one to the other — permanent, structural, and real.

> *"Selling the Truth means telling the truth."*

> *"Every human conversation is a selling conversation."*

